export const LANGS = { en: { label: "EN", dir: "ltr" }, ar: { label: "عربي", dir: "rtl" }, he: { label: "עב", dir: "rtl" } };

export function makeT(lang) {
  const dict = lang === "he" ? HE : lang === "en" ? EN : null;
  const words = lang === "he" ? HE_WORDS : lang === "en" ? EN_WORDS : null;
  const t = (s, vars) => {
    let out = dict ? dict[s] ?? s : s;
    if (vars) for (const [k, v] of Object.entries(vars)) out = out.split(`{${k}}`).join(v);
    return out;
  };
  const w = (s) => (words ? words[s] ?? s : s);
  const dur = (s) => (words ? String(s || "").replace("أيام", words["أيام"]).replace("خلال", words["خلال"]) : s);
  // tr = مش عربي (ترجمة) · he = عبري · en = إنجليزي
  return { lang, tr: lang !== "ar", he: lang === "he", en: lang === "en", dir: LANGS[lang]?.dir || "rtl", t, w, dur };
}

export function initialLang() {
  try {
    const q = new URLSearchParams(window.location.search).get("lang") || new URLSearchParams(window.location.hash.split("?")[1] || "").get("lang");
    if (LANGS[q]) {
      localStorage.setItem("lang", q);
      return q;
    }
    const saved = localStorage.getItem("lang");
    if (LANGS[saved]) return saved;
  } catch {
    /* تجاهل */
  }
  if (/^he|^iw/i.test(navigator.language || "")) return "he";
  return "en"; // الإنجليزي هو اللغة الأساسية
}
